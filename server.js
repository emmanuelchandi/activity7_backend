require("dotenv").config();
const express = require("express");
const cors = require("cors");
const pool = require("./db");

const app = express();

const PROJECT_NAME = "Campus Maintenance Requests";
const STUDENT_NUMBER = process.env.STUDENT_NUMBER || "202512538";

// Websites allowed to call the API from a browser. Postman and curl are not affected.
const origins = (process.env.CLIENT_ORIGINS || "")
  .split(",")
  .map((value) => value.trim())
  .filter(Boolean);

app.set("trust proxy", 1); // the host (Render) sits in front of the app and uses HTTPS
app.use(cors({ origin: origins }));
app.use(express.json());

